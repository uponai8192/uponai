// Regenerates src/lib/integrations.ts, the tile data for the homepage
// integrations hub. Run from the repo root with a local simple-icons copy:
//
//   npm install --no-save simple-icons
//   node scripts/generate-integrations.mjs src/lib/integrations.ts
//
// The scatter is deterministic from the seed below, so rerunning reproduces
// the checked-in layout exactly. Editing the brand lists, the seed or the
// spacing reshuffles every tile, so expect the whole file to change.
import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const si = require('simple-icons');
const siVersion = JSON.parse(fs.readFileSync(new URL('../node_modules/simple-icons/package.json', import.meta.url), 'utf8')).version;
const by = {};
for (const i of Object.values(si)) by[i.slug] = i;

const svgSlugs = ['gmail','googlecalendar','hubspot','zendesk','shopify','quickbooks','zoom','googledrive','dropbox','notion','wordpress','woocommerce','intercom','trello','mailchimp','paypal','stripe','calendly','asana','jira','clickup','box','square','zoho','airtable','zapier','make','googlesheets','whatsapp','googlemeet','xero','aircall','n8n','messenger','webflow','typeform'];

// Brands simple-icons does not carry, drawn as lettered tiles instead.
const monos = [
  ['Slack','#E01E5A','S'], ['Microsoft Teams','#6264A7','T'], ['Outlook','#0078D4','O'],
  ['Salesforce','#00A1E0','SF'], ['GoHighLevel','#3B82F6','HL'], ['Pipedrive','#25B35F','P'],
  ['ServiceNow','#62D84E','now'], ['Twilio','#F22F46','Tw'], ['Freshdesk','#25C16F','F'],
  ['RingCentral','#FF8800','RC'], ['monday.com','#FF3D57','M'], ['DocuSign','#FFCC22','DS'],
];

// Very dark marks are redrawn near-white so they read on the dark band.
function lum(hex) {
  const n = parseInt(hex, 16);
  const c = [n >> 16, (n >> 8) & 255, n & 255].map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}

const items = [
  ...svgSlugs.map((s) => {
    const i = by[s]; if (!i) throw new Error(s);
    return { name: i.title, color: lum(i.hex) < 0.06 ? '#E8EEFC' : '#' + i.hex, path: i.path };
  }),
  ...monos.map(([name, color, mark]) => ({ name, color, mark })),
];

// Deterministic scatter on a 1600x900 stage, keeping clear of the headline.
let seed = 7;
const rnd = () => ((seed = (seed * 16807) % 2147483647) - 1) / 2147483646;
const HUB = { x: 800, y: 400 };
const nodes = [];
const inKeepOut = (x, y) => ((x - 800) / 390) ** 2 + ((y - 585) / 315) ** 2 < 1 || (Math.abs(x - 800) < 170 && Math.abs(y - HUB.y) < 60);
let guard = 0;
while (nodes.length < items.length && guard++ < 200000) {
  const x = 70 + rnd() * 1460, y = 50 + rnd() * 800;
  if (inKeepOut(x, y)) continue;
  if (nodes.some((n) => Math.hypot(n.x - x, n.y - y) < 116)) continue;
  nodes.push({ x: Math.round(x), y: Math.round(y), d: +(0.35 + rnd() * 0.65).toFixed(2), t: +(rnd() * 6).toFixed(2) });
}
if (nodes.length < items.length) throw new Error('only ' + nodes.length);
// Shuffle item order so brands are mixed across the stage.
const order = items.map((_, i) => i).sort(() => rnd() - 0.5);

// Wire the nearer third of nodes to the hub, skipping the cone below it
// that the headline occupies.
const wired = new Set(
  nodes
    .map((n, i) => ({ i, dist: Math.hypot(n.x - HUB.x, n.y - HUB.y), ang: (Math.atan2(n.y - HUB.y, n.x - HUB.x) * 180) / Math.PI }))
    .filter((n) => !(n.ang > 35 && n.ang < 145))
    .sort((a, b) => a.dist - b.dist)
    .slice(0, 16)
    .map((n) => n.i),
);

const out = nodes.map((n, k) => ({ ...items[order[k]], x: n.x, y: n.y, depth: n.d, delay: n.t, wired: wired.has(k) }));

const ts = `// Generated by scripts/generate-integrations.mjs from simple-icons ${siVersion} (CC0).
// Brands that simple-icons does not carry (Microsoft, Slack, Salesforce and
// others) are drawn as lettered tiles in their brand colour. Positions are
// fixed points on a 1600x900 stage, scattered clear of the headline in the
// middle. Edit the script rather than this file.

export type Integration = {
  name: string;
  color: string;
  /** 24x24 SVG path; absent for lettered tiles. */
  path?: string;
  /** Lettering for brands without an icon path. */
  mark?: string;
  x: number;
  y: number;
  /** 0.35 (far) to 1 (near): drives size, brightness and parallax. */
  depth: number;
  /** Float animation offset in seconds. */
  delay: number;
  /** Draws a connection line to the hub. */
  wired: boolean;
};

export const INTEGRATION_HUB = { x: ${HUB.x}, y: ${HUB.y} };

export const integrations: Integration[] = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(process.argv[2], ts);
console.log(out.length, 'nodes,', wired.size, 'wired');
